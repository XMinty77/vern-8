#!/usr/bin/env python3
"""Generate the opcodes package from the ISA table.

Usage: python3 scripts/gen_opcodes.py docs/instructions.csv rtl/opcodes.sv

One `localparam logic [7:0]` per CSV row, named in UpperCamelCase (ILA becomes
Ila), grouped by the Unit column (in the order units first appear), with `?`
for every imm4 bit.
"""

import csv
import sys

BITS = [f"b{i}" for i in range(7, -1, -1)]  # CSV columns, MSB first


def fail(msg):
    sys.exit(f"gen_opcodes: {msg}")


def read_rows(csv_path):
    with open(csv_path, newline="") as f:
        rows = list(csv.DictReader(f))

    names = set()
    for row in rows:
        name = row["Name"]
        if not name.isidentifier():
            fail(f"bad instruction name {name!r}")
        if name in names:
            fail(f"duplicate instruction {name}")
        names.add(name)
        if not row["Unit"]:
            fail(f"{name} has no Unit")
        for b in BITS:
            if row[b] not in ("0", "1", "imm4"):
                fail(f"{name} {b} is {row[b]!r}, expected 0, 1 or imm4")
    return rows


def const_name(name):
    return "".join(part.capitalize() for part in name.split("_"))


def bit_string(row):
    return "".join("?" if row[b] == "imm4" else row[b] for b in BITS)


def generate(rows, csv_path):
    width = max(len(const_name(r["Name"])) for r in rows)

    def const(row):
        return f"  localparam logic [7:0] {const_name(row['Name']):<{width}} = 8'b{bit_string(row)};"

    units = []
    for row in rows:
        if row["Unit"] not in units:
            units.append(row["Unit"])

    out = [
        f"// Generated by scripts/gen_opcodes.py from {csv_path}. Do not edit.",
        "",
        "package opcodes;",
    ]
    for unit in units:
        members = [r for r in rows if r["Unit"] == unit]
        with_imm = [r for r in members if "?" in bit_string(r)]
        without_imm = [r for r in members if "?" not in bit_string(r)]

        out += ["", f"  // ================== {unit} ==================", ""]
        if with_imm and without_imm:
            out.append("  // Opcodes with immediates")
            out += [const(r) for r in with_imm]
            out += ["", "  // Opcodes with no immediates"]
            out += [const(r) for r in without_imm]
        else:
            out += [const(r) for r in members]

    out += ["", "endpackage", ""]
    return "\n".join(out)


def main():
    if len(sys.argv) != 3:
        fail("usage: gen_opcodes.py <instructions.csv> <output.sv>")
    csv_path, out_path = sys.argv[1], sys.argv[2]

    text = generate(read_rows(csv_path), csv_path)
    # Written only once everything above succeeded, so an error never leaves
    # a half-written package behind.
    with open(out_path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
